@pytest.mark.parametrize("text", [
    "Search results are returned within [response time to be confirmed - AMB-1].",
    "Search results are returned within a specified response time.",
    "Search results are returned within the required time limit.",
    "Search results are returned within a response time that is TBD.",
])
def test_placeholder_criterion_marked_explicit_by_the_model_becomes_blocked_assumption(text):
    out = {"ambiguities": [{"id": "AMB-1", "text": "fast", "issue": "no response-time target",
                            "clarification_question": "How fast?", "severity": "high"}],
           "assumptions": [],
           "acceptance_criteria": [ac("AC-1", text, source="explicit"),
                                   ac("AC-2", "Search results include categories and brands, not only products.")],
           "test_scenarios": [search_tc("TC-001", "AC-1", "positive", "Search responds"),
                              search_tc("TC-002", "AC-2", "positive", "Brand in results"),
                              search_tc("TC-003", "AC-2", "negative", "Unknown term", expected="No results are returned")],
           "not_applicable": []}
    pipeline, _ = make_pipeline([out])
    r = run(pipeline.generate(SEARCH))
    a1 = r.acceptance_criteria[0]
    assert a1.source == "assumption"
    asm = next(a for a in r.assumptions if a.id in a1.assumption_ids)
    assert "unresolved placeholder" in asm.reason
    l1 = link(r, "AC-1")
    assert l1.status == "needs_clarification" and l1.blocked_by
    assert "AMB-1" not in a1.description or "AMB-1" in l1.blocked_by  # references are rewritten to final ids
    # blocked placeholder counts in the denominator: 1 of 2 validated, not "1 of 1 = 100 %"
    assert r.coverage.coverage_percent == 50.0


