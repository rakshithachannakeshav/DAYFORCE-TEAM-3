def test_all_model_tests_invalid_every_time_does_not_fail_the_request():
    """Real run: v1.4 validation removed every model test on all 3 attempts -> HTTP 502.
    Now the repair prompt explains each removal, and the usable criteria are kept."""
    taut = json.loads((DATA / "qwen_password_reset_run2.json").read_text())
    taut["test_scenarios"] = [t for t in taut["test_scenarios"] if t["test_type"] == "positive"]  # only tautologies
