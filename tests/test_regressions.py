"""Regression tests for problems found in real qwen2.5:3b outputs (pipeline v1.3).

The two ``replay`` tests feed the model's actual answers (tests/data/) back through the
pipeline. Every pipeline call in these tests is also checked by
``conftest.assert_consistent`` (traceability, coverage, gaps and warnings must agree).
"""

from __future__ import annotations

import copy
