DATA = Path(__file__).parent / "data"
SEARCH = RequirementInput(
    requirement_id="REQ-202", title="Product search",
    description="The search should be fast and user-friendly and return relevant products, categories, brands etc.",
)
PASSWORD = RequirementInput(
    requirement_id="REQ-101", title="Password reset via email", actor="registered user",
    description="As a registered user, I want to reset my password using a link sent to my email so that I can "
                "regain access to my account.",
    business_rules=list(PASSWORD_RULES),
)
SEEDED = {
    "AC-1": "The reset link expires 30 minutes after it is sent.",
    "AC-2": "The new password must be between 8 and 64 characters.",
    "AC-3": "The new password must contain at least 1 digit.",
    "AC-4": "A user can request at most 3 reset emails per hour.",
    "AC-5": "The new password must not equal the current password.",
}


def link(result, ac_id):
    return next(x for x in result.traceability if x.acceptance_criterion_id == ac_id)


def warned(result, text):
    return any(text in w for w in result.metadata.warnings)


def search_tc(*a, **k):
    return {**tc(*a, **k), "requirement_id": "REQ-202"}


