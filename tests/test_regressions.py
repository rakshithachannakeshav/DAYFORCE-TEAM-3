# Replays of real model output
# --------------------------------------------------------------------------- #
def test_replay_real_password_reset_output():
    out = json.loads((DATA / "qwen_password_reset_run.json").read_text())
    pipeline, _ = make_pipeline([out], supplements=0)
    r = run(pipeline.generate(PASSWORD))

    # 6. fixed IDs and wording preserved; outcome of each fixed criterion is the rule itself
    assert {a.id: a.description for a in r.acceptance_criteria} == SEEDED
    assert all(a.then == a.description and a.source == "explicit" for a in r.acceptance_criteria)
    assert warned(r, "AC-4: model-written 'then' replaced")  # was "prompted to wait an hour"
    # 3. template text copied from the prompt is gone (it had wrongly set needs_clarification)
    assert not any("unclear phrase" in a.text for a in r.ambiguities)
    assert r.needs_clarification is False
    # 2. TC-001 clicked the link WITHIN 30 minutes and expected "no longer valid" -> removed, not relabelled
    assert "TC-001" not in {t.test_case_id for t in r.test_scenarios}
    assert warned(r, "TC-001 removed: contradictory - it uses valid input but expects a rejection")
    # TC-004 (positive) expected "prompted to wait an hour" for an in-limit request -> removed too
    assert warned(r, "TC-004 removed: contradictory")
    # 6. boundary tests: exactly one per stated limit, all generated by code
    bounds = [t for t in r.test_scenarios if t.test_type == "boundary"]
    assert len(bounds) == 4 and all(t.automation.rationale.startswith("Deterministic") for t in bounds)
    # 4/5. coverage reflects exactly what is missing
    assert [link(r, i).status for i in SEEDED] == ["partial", "validated", "validated", "partial", "validated"]
    # AC-1's only "negative" was the contradictory TC-001, so AC-1 honestly lacks both
    assert link(r, "AC-1").missing == ["positive test", "negative test"]
    assert link(r, "AC-4").missing == ["positive test"]
    assert r.coverage.coverage_percent == 60.0 and r.coverage.generated_coverage_percent == 100.0


def test_replay_real_ambiguous_search_output():
    out = json.loads((DATA / "qwen_ambiguous_search_run.json").read_text())
    pipeline, client = make_pipeline([out])
    r = run(pipeline.generate(SEARCH))

    ac1, ac2 = r.acceptance_criteria  # "...within a specified response time" / "...does not return irrelevant..."
    # 1. "a specified response time" is an unresolved placeholder -> not explicit, blocked
    assert ac1.source == "assumption" and ac1.assumption_ids
    assert link(r, "AC-1").status == "needs_clarification"
    fast = next(a.id for a in r.ambiguities if "'fast'" in a.issue)
    relevant = next(a.id for a in r.ambiguities if "'relevant'" in a.issue)
    assert link(r, "AC-1").blocked_by == [fast]
    assert ac2.source == "explicit" and link(r, "AC-2").blocked_by == [relevant]
    # 4. nothing validated; blocked criteria are in the denominator, never in the numerator
    assert r.coverage.validated_acceptance_criteria == 0 and r.coverage.coverage_percent == 0.0
    assert r.coverage.blocked_acceptance_criteria == 2
    # 5. gap text, missing and blocked_by name the same ambiguity
    assert link(r, "AC-1").missing == [f"clarification of {fast} (performance target)"]
    assert f"AC-1 cannot be validated until {fast} (performance target) is clarified" in r.coverage.gaps
    assert f"AC-2 cannot be validated until {relevant} (irrelevant) is clarified" in r.coverage.gaps
    assert len(client.calls) == 1  # no tests are requested for blocked criteria


