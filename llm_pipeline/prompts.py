"""Stage 3 - Prompt engineering.

Design principles (see docs/LLM_PIPELINE.md for the full rationale):
1. Role + task framing: the model acts as a senior QA engineer.
2. Grounding rules: never invent business rules, values, or concepts. Vague
   words are NOT converted into numbers; they become ambiguities and
   placeholders. Anything assumed is marked ``source: "assumption"``.
3. Rule anchoring: criteria for explicit business rules are fixed by code
   (one per rule clause, exact wording); the model writes Given/When/Then and
   tests for them, and may only add criteria stated in the description.
4. Test validity: a negative test must change the input or condition - not
   just flip the expected result. If none can exist, the model explains why
   in ``not_applicable`` instead of inventing one.
5. Division of labour: boundary tests for stated limits are generated by code,
   so the model is told not to spend tokens on them.
6. Output budget: hard caps on item counts and string length (a 3B model on an
   M1 MacBook Air writes ~24 tokens/s).
7. Precise repair: coverage gaps are sent back as a numbered task list
   ("AC-3 needs ONE negative test ..."), at most a few tasks per request.
"""

from __future__ import annotations

import json
from typing import TYPE_CHECKING

from .schemas import AcceptanceCriterion, Ambiguity, RequirementInput, TestScenario

if TYPE_CHECKING:  # pragma: no cover
    from .coverage import Context, Task

PROMPT_VERSION = "1.4"

# Output budget - also enforced as maxItems in the JSON schema (pipeline.py).
MAX_AMBIGUITIES = 5
MAX_ASSUMPTIONS = 5
MAX_ACCEPTANCE_CRITERIA = 6
MAX_EXTRA_CRITERIA = 2  # criteria beyond the seeded business-rule criteria
MAX_TEST_SCENARIOS = 16
MAX_TASKS_PER_SUPPLEMENT = 4
MAX_TASK_ATTEMPTS = 2  # a task the model failed is asked once more, with the reason it was rejected

_ROLE_AND_GROUNDING = """You are a senior QA engineer and requirements analyst.

## Grounding rules (most important)
- Use ONLY information stated in the requirement. Do NOT invent business rules, limits, durations, response times, password policies, fields, roles, or error messages.
- Every number you write in a criterion or expected result MUST appear in the requirement. Never add a number the requirement does not state.
- Vague words (fast, user-friendly, relevant, secure ...) must NOT be turned into numbers. Record an ambiguity with a clarification question, and if you write a criterion for it, use a placeholder: e.g. "Search results are returned within [response time to be confirmed - AMB-1]" with "source": "assumption".
  Example: "The search should be fast" -> ambiguity "fast: no response-time target", question "What is the maximum acceptable response time?". NOT "within 2 seconds".
- Anything you had to assume goes into "assumptions"; a criterion that depends on it has "source": "assumption" and lists the assumption IDs. Only criteria stated in the requirement use "source": "explicit"."""

_SCENARIO_RULES = """## Test scenario rules
- test_type must be one of: "positive", "negative", "boundary", "edge_case".
- positive = valid input / conditions, the behaviour succeeds as stated.
- negative = invalid input, a violated rule, or a failure condition, and the system handles it (rejects, shows an error, does not change state). A negative test MUST use different input or conditions from the positive test. Never copy a positive test and just reverse its expected result.
- A negative test's INPUT must be genuinely invalid or break the stated rule (too short, no digit, 4th request in the hour, link used after expiry, same as current password). Valid input with an error expected is WRONG; invalid input with success expected is WRONG.
- If a criterion has no meaningful negative case (nothing a user could violate), do NOT invent one: add {"acceptance_criterion_id": "AC-n", "test_type": "negative", "reason": "..."} to "not_applicable".
- expected_result may only state behaviour the requirement gives. If it does not say HOW a rejection is shown, write "the request is rejected" / "the change is not applied" - never invent error-message text, status codes, wait times, redirects, or emails.
- "edge_case" tests cover unusual but valid situations ONLY when relevant.
- priority: "high", "medium" or "low" (core happy path and security = high).
- 2-4 short imperative test_steps. expected_result is ONE observable outcome.
- automation.level: "unit", "api", "integration", "ui" or "manual" - the LOWEST level that can verify it. suggested_tool examples: pytest, Playwright, Postman, JUnit.
- Every test's "requirement_id" is the given requirement ID; its "acceptance_criterion_id" is an existing criterion ID.
- Keep every string under 25 words. Never repeat a test."""

_SCENARIO_SHAPE = (
    '{"test_case_id": "TC-001", "title": "...", "requirement_id": "<REQ ID>", "acceptance_criterion_id": "AC-1", '
    '"test_type": "positive|negative|boundary|edge_case", "preconditions": ["..."], "test_steps": ["..."], '
    '"test_data": ["..."], "expected_result": "...", "priority": "high|medium|low", '
    '"automation": {"automatable": true, "level": "unit|api|integration|ui|manual", "suggested_tool": "...", '
    '"rationale": "..."}}'
)

SYSTEM_PROMPT = f"""{_ROLE_AND_GROUNDING}

Your job: turn ONE product requirement into precise acceptance criteria and test scenarios.

## Acceptance criteria rules
- If "Fixed acceptance criteria" are listed, use EXACTLY those IDs and that wording, and write given/when for each; their "then" is the rule itself. Do not split, merge, or reword them.
- You may add at most {MAX_EXTRA_CRITERIA} further criteria, numbered after the fixed ones, ONLY for behaviour stated in the description.
- Each criterion is ONE measurable pass/fail statement written as Given / When / Then. A criterion states a rule, not a single test case.

{_SCENARIO_RULES}
- Every criterion needs one "positive" and one "negative" test (or a not_applicable entry with the reason).
- At most {MAX_TEST_SCENARIOS} test scenarios in total.

## Traceability rules
- IDs: ambiguities "AMB-1", assumptions "ASM-1", acceptance criteria "AC-1", tests "TC-001" (sequential, unique).

## Output rules
- Respond with ONE compact JSON object only. No markdown, no code fences, no commentary.
- Keys in this order: "ambiguities" (max {MAX_AMBIGUITIES}), "assumptions" (max {MAX_ASSUMPTIONS}), "acceptance_criteria", "test_scenarios", "not_applicable". Use [] when a list is empty.

## JSON shape
{{
  "ambiguities": [{{"id": "AMB-1", "text": "exact unclear phrase", "issue": "why unclear", "clarification_question": "question for the product owner", "severity": "high|medium|low"}}],
  "assumptions": [{{"id": "ASM-1", "statement": "what you assumed", "reason": "which gap it fills"}}],
  "acceptance_criteria": [{{"id": "AC-1", "description": "measurable statement", "given": "...", "when": "...", "then": "...", "source": "explicit|assumption", "assumption_ids": []}}],
  "test_scenarios": [{_SCENARIO_SHAPE}],
  "not_applicable": [{{"acceptance_criterion_id": "AC-1", "test_type": "negative", "reason": "..."}}]
}}

## How to label tests (example from a DIFFERENT product - do not copy its content)
Rule: "A coupon code can be used once per customer."
- positive: first use of a valid coupon by a customer -> discount applied.
- negative: the SAME customer uses the coupon a second time -> rejected with an error. (Different condition from the positive test, not just a reversed result.)"""

SUPPLEMENT_SYSTEM_PROMPT = f"""{_ROLE_AND_GROUNDING}

Your job: an existing test suite has specific coverage gaps. Complete ONLY the numbered tasks you are given - one test per task.

{_SCENARIO_RULES}

## Output rules
- Respond with ONE compact JSON object only: {{"test_scenarios": [ ... ], "not_applicable": [ ... ]}}. No markdown, no commentary.
- Each scenario has this shape: {_SCENARIO_SHAPE}
- Each not_applicable entry: {{"acceptance_criterion_id": "AC-n", "test_type": "negative", "reason": "why no negative test can exist"}}"""


def build_user_prompt(req: RequirementInput, rule_ambiguities: list[Ambiguity], ctx: "Context") -> str:
    lines = [f"Requirement ID: {req.requirement_id}"]
    if req.title:
        lines.append(f"Title: {req.title}")
    lines.append(f"Description:\n{req.description}")
    if req.actor:
        lines.append(f"Primary actor: {req.actor}")
    if req.business_rules:
        lines.append("Explicit business rules:\n" + "\n".join(f"- {r}" for r in req.business_rules))
    if req.context:
        lines.append(f"Context:\n{req.context}")

    if ctx.seeds:
        lines.append(
            "Fixed acceptance criteria (one per business-rule clause - use these IDs and this wording):\n"
            + "\n".join(f"- {s.id}: {s.text}" for s in ctx.seeds)
            + f"\nAny additional criterion from the description starts at AC-{len(ctx.seeds) + 1}."
        )
    if ctx.limits:
        lines.append(
            "Boundary tests for these limits are generated automatically - do NOT write boundary tests for them:\n"
            + "\n".join(f"- {lim.phrase}" for lim in ctx.limits)
        )
    if ctx.leftover_boundaries:
        lines.append(
            "Write ONE boundary test (values just below, at, and just above) for each of these limits:\n"
            + "\n".join(f"- {b}" for b in ctx.leftover_boundaries)
        )
    if rule_ambiguities:
        lines.append(
            "Ambiguities already detected by static analysis (confirm, refine, add others; never resolve them by inventing values):\n"
            + "\n".join(f"- {a.text}: {a.issue}" for a in rule_ambiguities)
        )

    lines.append("Generate the JSON object now.")
    return "\n\n".join(lines)


def build_repair_prompt(errors: list[str], truncated: bool = False) -> str:
    """Correction message sent when a full generation is unusable.

    The previous (bad) output is sent just before this as an ``assistant``
    message, so the model can correct it instead of starting from scratch.
    """
    parts = ["Your previous response was rejected by the validator."]
    if truncated:
        parts.append(
            "It was cut off because it was too long. Return a SHORTER response: at most 10 test scenarios, "
            "with concise steps."
        )
    if errors:
        parts.append("Fix ALL of these problems:\n" + "\n".join(f"- {e}" for e in errors[:15]))
    parts.append(
        "Return the complete corrected JSON object only, with keys "
        '"ambiguities", "assumptions", "acceptance_criteria", "test_scenarios", "not_applicable". '
        "No markdown, no explanation."
    )
    return "\n\n".join(parts)


def build_supplement_prompt(
    requirement_id: str,
    acceptance_criteria: list[AcceptanceCriterion],
    existing: list[TestScenario],
    tasks: list["Task"],
    next_tc_number: int,
) -> str:
    """Small, targeted request: exactly the listed tasks, nothing else."""
    task_acs = {t.ac_id for t in tasks}
    acs = [ac for ac in acceptance_criteria if ac.id in task_acs]
    related = [tc for tc in existing if tc.acceptance_criterion_id in task_acs]
    parts = [
        f"Requirement ID: {requirement_id}",
        "Acceptance criteria involved:\n"
        + "\n".join(f"- {ac.id}: {ac.description} (Given {ac.given}; When {ac.when}; Then {ac.then})" for ac in acs),
    ]
    if related:
        parts.append(
            "Existing tests for these criteria (do NOT repeat them; negative tests must use different steps or data):\n"
            + "\n".join(f"- {tc.test_case_id} [{tc.test_type}] {tc.acceptance_criterion_id}: {tc.title} | steps: "
                        f"{'; '.join(tc.test_steps)[:120]}" for tc in related)
        )
    parts.append("Tasks:\n" + "\n".join(f"{i}. {t.text}" for i, t in enumerate(tasks, start=1)))
    parts.append(
        f"Number new tests from TC-{next_tc_number:03d}. Return "
        f'{{"test_scenarios": [...], "not_applicable": [...]}} with at most {len(tasks)} tests.'
    )
    return "\n\n".join(parts)


def prompt_debug_dump(req: RequirementInput, rule_ambiguities: list[Ambiguity], ctx: "Context") -> str:
    """Handy for the demo / report: shows the exact messages sent to the model."""
    return json.dumps(
        {
            "prompt_version": PROMPT_VERSION,
            "system": SYSTEM_PROMPT,
            "user": build_user_prompt(req, rule_ambiguities, ctx),
        },
        indent=2,
    )
